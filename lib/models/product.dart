class Product {
  final String id;
  final String name;
  final String description;
  final String price;
  final String image;
  final String category;
  final String weight;
  final String seller;

  Product({
    required this.id,
    required this.name,
    required this.description,
    required this.price,
    required this.image,
    required this.category,
    required this.weight,
    required this.seller,
  });
}
